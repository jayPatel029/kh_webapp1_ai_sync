  const filterDataByTimeRange = (data) => {
    // Set time range in local time (not UTC)
    const start = new Date(selectionRange.startDate);
    start.setHours(0, 0, 0, 0);

    const end = new Date(selectionRange.endDate);
    end.setHours(23, 59, 59, 999);

    console.log("Date range (local):", start, "to", end);

    return data.filter((item) => {
      const itemDate = new Date(item.date);
      itemDate.setHours(0, 0, 0, 0); // Ensure clean date
      return itemDate >= start && itemDate <= end;
    });
  };

